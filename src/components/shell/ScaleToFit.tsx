/**
 * 화면 전체를 **기준 해상도(15" · 1512×982) 캔버스**로 놓고, 실제 화면 크기에 맞춰
 * 가로세로 비율을 유지한 채 통째로 줄이거나 키운다.
 *
 * 2026-08-12, 사용자 지시 — "13인치랑 15인치에서 다르게 보인다" 문제를
 * 컴포넌트별 반응형(브레이크포인트마다 폰트·여백 다시 정하기) 대신 이 방식으로
 * 푼다: 안쪽 내용은 **항상 1512×982 라고 믿고** 그리고, 실제 화면 크기에 맞춰
 * `transform: scale()` 로 시각적으로만 조절한다. 그래서
 * - 기존 px 계산(예: 화면1 카드 높이)이 실제 화면 크기와 무관하게 그대로 유효하다.
 * - 색·폰트·간격 값을 단 하나도 안 건드린다(디자인 시스템 금지 원칙과 충돌 없음).
 *
 * 배율은 CSS `min()`/`calc()` 로만 계산한다 — JS 로 리사이즈를 재는 순간 SSR
 * 첫 페인트에는 배율을 모르니(서버는 화면 크기를 모른다) 로드 직후 한 번
 * "커졌다 줄어드는" 깜빡임이 생긴다. CSS 는 브라우저가 페인트 시점에 바로
 * 계산해 그런 깜빡임이 없고, 리사이즈에도 별도 리스너 없이 따라온다.
 *
 * 🔴 **상한(`min(1, …)`)을 두지 않는다**(2026-08-12 사용자 지시로 제거).
 *    기준보다 큰 화면(외부 모니터·프로젝터)에서는 1 을 넘겨 **더 크게** 그린다.
 *    상한이 있으면 큰 화면일수록 가운데 작은 사각형만 쓰고 사방이 여백이 됐다 —
 *    발표를 큰 화면으로 하는 이상 그게 손해다. 글자·아이콘은 벡터라 확대해도
 *    선명하다(래스터 이미지를 넣게 되면 그때는 원본 해상도를 확인할 것).
 *
 * 🔴 캔버스에 `flexShrink: 0` 이 필수다 — 없으면 부모 flex 가 화면이 작을 때
 *    박스 자체를 눌러 찌그러뜨리려 하고, 그러면 안쪽 레이아웃이 진짜로
 *    재계산돼서(우리가 피하려던 바로 그 반응형 리플로우) `scale()` 의 의미가
 *    없어진다. 박스 크기는 절대 안 바뀌고 시각적으로만 줄어야 한다.
 *
 * 🔴 **배율은 기준 캔버스로 재고, 논리 크기는 실제 화면만큼 준다**(2026-08-12 보강).
 *    처음엔 박스를 `1512 × 982` 로 **고정**했는데, 그러면 캔버스 비(1.540)와 다른
 *    화면에서 남는 쪽이 통째로 여백이 된다 — 레터박스다. 실측: 1920×955 화면에서
 *    `min()` 이 세로(955/982 = 0.9725)를 고르고 가로는 1512×0.9725 = **1470** 만
 *    쓰여 **좌우에 225px 씩 흰 띠**가 생겼다.
 *
 *    고친 방식은 **배율을 안 건드린다** — 위 의도(기준 15" 로 재고, 작으면 비율
 *    유지 축소, 크면 확대, 상한 없음, CSS 만으로)가 그대로다. 바뀐 건 논리 크기를
 *    `화면 ÷ 배율` 로 준다는 것뿐이다: 0.9725 배로 그릴 거면 논리 폭을
 *    1920/0.9725 = 1974.28px 로 잡아야 렌더 결과가 정확히 화면을 채운다.
 *    가로·세로를 따로 늘리는 것(`scale(a, b)`)이 아니라 **한 배율을 그대로 두고
 *    지면만 넓히는 것**이라 찌그러지지 않는다. 실측: 렌더 1920×955, 여백 0.
 *
 *    좁은 화면에선 `min()` 이 가로를 고르므로 논리 폭이 정확히 `baseWidth` 로
 *    떨어진다 — 기준 캔버스는 여전히 하한이다. 안쪽 레이아웃은 가로 flex 라
 *    지면이 넓어져도 안 깨진다(세로는 `h-full` + `min-h-0` 로 이미 늘어난다).
 *
 * 🔴 **가운데 정렬을 걷어내고 좌상단에 못박는다**(2026-08-14, 배포본에서 헤더가
 *    잘려 보고됨). 예전에는 부모가 `align-items:center` 로 캔버스를 **가운데**
 *    두고, 캔버스 크기는 `100dvw`·`100dvh` 로 **자기가** 정했다 — 뷰포트를 재는
 *    자리가 둘이었다. 둘이 어긋나면 그 차이의 **절반이 위로** 밀리고, 캔버스
 *    맨 앞에 있는 헤더가 그걸 통째로 뒤집어쓴다.
 *
 *    실측(2026-08-14, 824×832) — 배포본과 로컬이 `--fit`(0.544974)도 논리 크기
 *    (1512×1527)도 **똑같은데** 렌더 위치만 갈렸다:
 *      · 로컬   `renderedTop = +0.01`
 *      · 배포본 `renderedTop = −31.99`  ← 헤더 위쪽 32px 가 화면 밖
 *    렌더 높이는 양쪽 다 832 = `dvh` 였다. 832 짜리를 832 안에 가운데 두면 top 은
 *    0 이어야 하므로, 배포본에서는 **부모가 64px 짧았다**(384−416 = −32).
 *
 *    고치는 방법은 부모를 고치는 게 아니라 **부모에게 안 묻는 것**이다. 캔버스는
 *    이미 「화면을 정확히 채우는 크기」로 계산돼 있어서 가운데 정렬은 정상일 때
 *    **아무 일도 안 한다** — 없어도 결과가 같고, 어긋났을 때만 해를 끼친다.
 *    그래서 원점을 `top left` 로 놓고 정렬을 `flex-start` 로 내린다. 이제 렌더
 *    결과는 부모 높이와 무관하게 항상 (0, 0) 에서 시작한다.
 *    ⚠ `transformOrigin` 과 정렬은 **한 벌이다.** 원점만 옮기고 정렬을 `center`
 *      로 두면 축소분만큼 다시 밀린다.
 */
export function ScaleToFit({
  baseWidth,
  baseHeight,
  children,
}: {
  baseWidth: number;
  baseHeight: number;
  children: React.ReactNode;
}) {
  return (
    <div
      style={{
        position: "fixed",
        inset: 0,
        overflow: "hidden",
        display: "flex",
        alignItems: "flex-start",
        justifyContent: "flex-start",
        background: "var(--canvas-soft)",
      }}
    >
      <div
        style={
          {
            // 🔴 나누는 쪽에 `px` 를 꼭 붙인다 — 길이 ÷ 숫자(단위 없음)는 CSS 에서
            //    다시 길이가 된다(숫자가 안 됨). `scale()` 은 숫자만 받으므로
            //    길이 ÷ 길이(둘 다 `px`)라야 나눗셈이 숫자로 떨어진다. 하나라도
            //    단위가 안 맞으면 `min()` 인자 타입이 안 섞여 선언 전체가 무효가
            //    되고, 브라우저는 `transform: none` 으로 조용히 되돌린다(실측 확인).
            "--fit": `min(calc(100dvw / ${baseWidth}px), calc(100dvh / ${baseHeight}px))`,
            // 논리 크기 = 화면 ÷ 배율. 배율은 위에서 이미 정해졌고 여기서 다시
            // 정하지 않는다 — 두 곳에서 정하면 언젠가 한쪽만 바뀐다.
            width: "calc(100dvw / var(--fit))",
            height: "calc(100dvh / var(--fit))",
            flexShrink: 0,
            transform: "scale(var(--fit))",
            transformOrigin: "top left",
          } as React.CSSProperties
        }
      >
        {children}
      </div>
    </div>
  );
}
