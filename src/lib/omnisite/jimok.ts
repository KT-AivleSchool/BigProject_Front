/**
 * 지목(地目) 부호 한 글자를 **정식 명칭**으로 바꾼다.
 *
 * 지적공부의 지목은 「공간정보의 구축 및 관리 등에 관한 법률 시행령 제58조」의
 * **28종**으로 정해져 있고, 지적도·`topN.csv` 에는 그 **부호 한 글자**로 들어온다.
 * 보고서를 읽는 사람은 공무원이라 「대」·「학」·「구」 같은 한 글자를 그대로 두면
 * 무슨 땅인지 알 수 없다(2026-08-14 사용자 지시).
 *
 * 🔴 **부호와 첫 글자가 다른 것들이 있다.** 여기가 이 표를 손으로 못 쓰는 이유다.
 *    공장용지=`장` · 학교용지=`학` · 주차장=`차` · 주유소용지=`주` · 창고용지=`창`
 *    · 철도용지=`철` · 하천=`천` · 유원지=`원` · 종교용지=`종` · 수도용지=`수`.
 *    「주차장→차」와 「주유소용지→주」처럼 **첫 글자가 겹쳐서 일부러 다른 글자를
 *    쓴 쌍**이 있으므로, 「첫 글자를 따면 된다」는 규칙으로 줄이면 틀린다.
 *
 * 🔴 **`대` 는 「대로」가 아니라 「대지」다.** 사용자가 처음 예시를 「학교·공원·대로」
 *    로 적었지만 그건 착오다 — 「대(垈)」는 건축물을 지을 수 있는 **대지**이고,
 *    「대로」는 도로의 폭 등급이라 지목에 없다. 도로는 부호 `도` 로 따로 있다.
 *    보고서에 「대로」라고 찍으면 **읽는 공무원이 필지 성격을 정반대로 이해한다**
 *    (건축 가능한 땅 ↔ 도로). 화면 4 도 이미 `대 → 대지` 로 쓰고 있었다.
 *
 * ⚠ 모르는 부호는 **지어내지 않고 받은 값을 그대로 돌려준다.** 지적도가 비표준
 *   코드를 담고 있을 때 그럴듯한 이름으로 바꾸면 그게 더 위험하다.
 */
const JIMOK: Readonly<Record<string, string>> = {
  전: "전",
  답: "답",
  과: "과수원",
  목: "목장용지",
  임: "임야",
  광: "광천지",
  염: "염전",
  대: "대지",
  장: "공장용지",
  학: "학교용지",
  차: "주차장",
  주: "주유소용지",
  창: "창고용지",
  도: "도로",
  철: "철도용지",
  제: "제방",
  천: "하천",
  구: "구거",
  유: "유지",
  양: "양어장",
  수: "수도용지",
  공: "공원",
  체: "체육용지",
  원: "유원지",
  종: "종교용지",
  사: "사적지",
  묘: "묘지",
  잡: "잡종지",
};

/**
 * 부호를 정식 명칭으로. 이미 정식 명칭이거나 모르는 값이면 **그대로** 돌려준다.
 *
 * ⚠ 빈 값은 빈 문자열이 아니라 `—` 로 돌려준다. 표에서 빈 칸은 「값이 0」인지
 *   「모른다」인지 구분이 안 된다.
 */
export function jimokLabel(code: string | null | undefined): string {
  const v = (code ?? "").trim();
  if (v === "") return "—";
  return JIMOK[v] ?? v;
}

/**
 * 백엔드가 만든 **문장 속에 박힌** 지목 부호를 명칭으로 바꾼다.
 *
 * `report.json` 의 `data_gap` 은 사람이 읽으라고 만든 문자열인데 지목만 부호로
 * 들어온다 — 실측 두 모양뿐이다(`api-samples/r_20260804_003/report.json`):
 *
 * ```
 * "dataset 01 · 지목 학"            → 「지목 X」 꼴
 * "철, 천, 구, 학, 유, 주, 사, 묘, 수"  → 부호만 쉼표로 늘어놓은 꼴
 * ```
 *
 * 🔴 **문장 전체를 훑어서 한 글자를 치환하면 안 된다.** 「학」·「대」·「공」은
 *    평범한 한국어 낱말의 일부이기도 해서(예: 「대상」의 `대`), 무차별 치환은
 *    엉뚱한 곳을 망가뜨린다. 그래서 **위 두 모양에만** 걸리게 좁혀 놨고,
 *    둘 다 아니면 **받은 문자열을 그대로 돌려준다.** 백엔드 문구가 바뀌면
 *    바뀐 그대로 나가는 게 맞다 — 반쯤 고쳐진 문장보다 낫다.
 */
export function jimokText(text: string): string {
  // ① 부호만 쉼표로 늘어놓은 것. **전부** 아는 부호일 때만 바꾼다.
  const tokens = text.split(",").map((t) => t.trim());
  if (tokens.length > 1 && tokens.every((t) => t in JIMOK)) {
    return tokens.map((t) => JIMOK[t]).join(", ");
  }
  // ② 「지목 X」 — 뒤에 한글이 더 붙지 않은 한 글자일 때만.
  return text.replace(/지목 ([가-힣])(?![가-힣])/g, (whole, code: string) =>
    code in JIMOK ? `지목 ${JIMOK[code]}` : whole,
  );
}
